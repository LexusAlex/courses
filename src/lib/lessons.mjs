import { catalogPages, indexCatalog } from '../data/catalog-tree.mjs';

/** @typedef {{ id: string, data: { title: string, draft?: boolean, durationMinutes?: number | null, sidebar?: { order?: number, hidden?: boolean } }, filePath?: string }} Doc */
/** @typedef {{ id: string, courseId: string, locale: 'ru' | 'en', path: string, title: string, moduleId?: string, durationMinutes?: number | null, order: number, sortPath: string }} Lesson */

/** @param {string} id */
export const normalizeDocId = (id) => id.replace(/\\/g, '/').replace(/\.(?:md|mdx)$/, '').replace(/(?:^|\/)index$/, '').replace(/^\/+|\/+$/g, '');

// Match autogenerated sidebar sorting: weighted directories, then stable path order.
const collator = new Intl.Collator('ru');
/** @param {Lesson[]} lessons @param {string} prefix @returns {Lesson[]} */
function sortFolder(lessons, prefix = '') {
  /** @type {Map<string, Lesson[]>} */
  const groups = new Map();
  for (const lesson of lessons) {
    const relative = lesson.sortPath.slice(prefix.length);
    const key = relative.includes('/') ? `${prefix}${relative.split('/')[0]}/` : lesson.sortPath;
    groups.set(key, [...(groups.get(key) ?? []), lesson]);
  }
  return [...groups.entries()].sort(([aPath, a], [bPath, b]) => {
    const aOrder = Math.min(...a.map((lesson) => lesson.order));
    const bOrder = Math.min(...b.map((lesson) => lesson.order));
    return aOrder === bOrder ? collator.compare(aPath, bPath) : aOrder - bOrder;
  }).flatMap(([path, items]) => path.endsWith('/') ? sortFolder(items, path) : items);
}

/** Published lesson sequences, excluding home/course/module overview pages.
 * @param {Doc[]} entries
 * @param {import('../data/catalog-tree.mjs').Category[]} roots
 * @returns {Lesson[]}
 */
export function indexLessons(entries, roots) {
  const structural = new Set(catalogPages(roots).map((entry) => entry.path));
  const { courseById } = indexCatalog(roots);
  /** @type {Map<string, Lesson[]>} */
  const groups = new Map();
  const seen = new Set();
  for (const entry of entries) {
    if (entry.data.draft || entry.data.sidebar?.hidden) continue;
    const path = normalizeDocId(entry.id);
    const match = /^(ru|en)\/(courses\/([^/]+)(?:\/(.+))?)$/.exec(path);
    if (!match) continue;
    const [, language, relativePath, courseId, relativeLesson] = match;
    const owner = courseById.get(courseId);
    if (!owner) throw new Error(`Lesson "${entry.id}": unknown course "${courseId}".`);
    if (structural.has(relativePath)) continue;
    if (!relativeLesson) throw new Error(`Lesson "${entry.id}" must be inside its course directory.`);
    const modules = owner.course.modules ?? [];
    const moduleId = modules.length ? relativeLesson.split('/')[0] : undefined;
    const moduleOrder = moduleId ? modules.findIndex((module) => module.id === moduleId) : 0;
    if (moduleOrder < 0 || (moduleId && !relativeLesson.includes('/'))) {
      throw new Error(`Lesson "${entry.id}": put lessons inside a declared course module.`);
    }
    if (seen.has(path)) throw new Error(`Duplicate lesson route "${path}".`);
    seen.add(path);
    const order = entry.data.sidebar?.order ?? Number.MAX_VALUE;
    if (!Number.isFinite(order)) throw new Error(`Lesson "${entry.id}": sidebar.order must be finite.`);
    const sourceRelative = entry.filePath?.replace(/\\/g, '/').split(`/courses/${courseId}/`)[1]?.replace(/\.(?:md|mdx)$/, '') ?? relativeLesson;
    const lesson = {
      id: `${courseId}/${relativeLesson}`, courseId, locale: /** @type {'ru' | 'en'} */ (language),
      path, title: entry.data.title, moduleId, durationMinutes: entry.data.durationMinutes, order,
      sortPath: moduleId ? sourceRelative.slice(moduleId.length + 1) : sourceRelative,
    };
    const group = `${language}/${courseId}/${moduleOrder}`;
    groups.set(group, [...(groups.get(group) ?? []), lesson]);
  }
  return [...groups.entries()].sort(([a], [b]) => {
    const [aLocale, aCourse, aModule] = a.split('/');
    const [bLocale, bCourse, bModule] = b.split('/');
    return aLocale.localeCompare(bLocale) || aCourse.localeCompare(bCourse) || Number(aModule) - Number(bModule);
  }).flatMap(([, lessons]) => sortFolder(lessons));
}
